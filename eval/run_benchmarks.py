"""Runs the whole benchmark matrix and writes docs/results.md.

    python eval/run_benchmarks.py --quick     # about 2 minutes: do this first
    python eval/run_benchmarks.py             # full matrix, about 6 minutes

Every configuration gets its own server process, so settings cannot leak between runs.
Raw per-run JSON goes to eval/results/ (git-ignored); the summary table goes to docs/results.md.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "eval" / "results"
DOCS = ROOT / "docs"
HANGOVER_MS = 600


class Server:
    """A throwaway gateway process with explicit settings (they override .env)."""

    def __init__(self, port: int, providers: str, mode: str):
        self.port = port
        self.providers = providers
        self.mode = mode
        self._proc: subprocess.Popen[bytes] | None = None
        self._log: Any = None

    def __enter__(self) -> Server:
        try:
            self._start()
        except BaseException:
            self._stop()
            raise
        return self

    def __exit__(self, *exc: object) -> None:
        self._stop()

    def _start(self) -> None:
        env = {
            **os.environ,
            "VGW_PROVIDERS": self.providers,
            "VGW_MODE": self.mode,
            "VGW_VAD": "synthetic",
            "VGW_LOG_LEVEL": "warning",
            "VGW_HANGOVER_MS": str(HANGOVER_MS),
            "VGW_BARGE_IN_MS": "200",
        }
        OUT.mkdir(parents=True, exist_ok=True)
        self._log = open(OUT / f"server-{self.port}.log", "wb")  # noqa: SIM115
        cmd = [sys.executable, "-m", "uvicorn", "vgw.server:app",
               "--port", str(self.port), "--log-level", "warning"]  # fmt: skip
        self._proc = subprocess.Popen(
            cmd, cwd=ROOT, env=env, stdout=self._log, stderr=subprocess.STDOUT
        )
        deadline = time.time() + 30
        while time.time() < deadline:
            if self._proc.poll() is not None:
                raise RuntimeError(f"server exited early; see {self._log.name}")
            try:
                if httpx.get(f"http://127.0.0.1:{self.port}/health", timeout=1).status_code == 200:
                    return
            except httpx.HTTPError:
                time.sleep(0.3)
        raise RuntimeError(f"server did not become healthy in 30 s; see {self._log.name}")

    def _stop(self) -> None:
        if self._proc is not None and self._proc.poll() is None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self._proc.kill()
                self._proc.wait()
        if self._log is not None:
            self._log.close()


def run_loadgen(port: int, label: str, scenario: str, sessions: int, turns: int) -> dict[str, Any]:
    cmd = [
        sys.executable, str(ROOT / "eval" / "loadgen.py"),
        "--url", f"ws://127.0.0.1:{port}/ws",
        "--sessions", str(sessions), "--turns", str(turns), "--scenario", scenario,
        "--hangover-ms", str(HANGOVER_MS), "--label", label, "--out", str(OUT),
    ]  # fmt: skip
    subprocess.run(cmd, cwd=ROOT, check=True)
    return json.loads((OUT / f"{label}.json").read_text(encoding="utf-8"))


# ----------------------------------------------------------------- formatting
def fmt(stats: dict[str, float] | None, key: str) -> str:
    return "-" if not stats else f"{stats[key]:.0f}"


def pct(value: float | None) -> str:
    return "-" if value is None else f"{value * 100:.0f}%"


def valid(r: dict[str, Any]) -> str:
    ok = r["loadgen"]["late_pct"] <= 1.0 and r["failures"] == 0 and not r["errors"]
    return "yes" if ok else "NO"


def table(headers: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return [*out, ""]


def write_results(runs: dict[str, dict[str, Any]], scale: list[int]) -> Path:
    lines = [
        "# Benchmark results",
        "",
        f"Generated by `python eval/run_benchmarks.py` on {time.strftime('%Y-%m-%d %H:%M')}.  ",
        f"Machine: {platform.platform()}, {os.cpu_count()} logical CPUs, "
        f"Python {platform.python_version()}.",
        "",
        "The server and the load generator ran on the **same machine**, so compare rows with each "
        "other rather than reading them as absolute capacity. A run is only marked valid if the "
        "load generator's own frames left on time (under 1% late) and no caller failed.",
        "",
        "**Definitions.** *Time to first audio (TTFA)* runs from the caller's last speech frame "
        f"to the first agent audio frame received. It includes the {HANGOVER_MS} ms endpointing "
        f"wait, so *overhead* below is TTFA minus {HANGOVER_MS} ms: what the gateway and the "
        "providers add on top.",
        "",
        "## 1. Scaling: the gateway on its own",
        "",
        "Provider set `bench`: silent audio and zero simulated provider latency, so ",
        "the numbers are the gateway's own cost.",
        "",
    ]
    rows = []
    for n in scale:
        r = runs[f"scale-n{n}"]
        t = r["ttfa_ms"]
        overhead = f"{t['p50'] - HANGOVER_MS:.0f}" if t else "-"
        rows.append([
            str(n), fmt(t, "p50"), fmt(t, "p95"), fmt(t, "p99"), overhead,
            str(r["server"]["cpu_pct_of_one_core"]), str(r["server"]["cpu_ms_per_session_second"]),
            str(r["server"]["rss_mb"]), f"{r['loadgen']['late_pct']}%", valid(r),
        ])  # fmt: skip
    lines += table(
        ["Sessions", "TTFA p50 ms", "p95", "p99", "Overhead p50 ms", "Server CPU (% of 1 core)",
         "CPU ms per session-second", "Memory MB", "Loadgen late frames", "Valid"],
        rows,
    )  # fmt: skip

    b = runs["barge-bench"]
    lines += [
        "## 2. Barge-in: how fast does the agent stop?",
        "",
        "Each caller speaks, lets the agent talk for 0.6 s, then talks over it. *Cut-off* is the "
        "time from the start of the interruption to the gateway telling the client to stop. "
        "*Stale frames* counts agent audio that still arrived after the stop signal (must be 0).",
        "",
    ]
    eff = b.get("efficiency") or {}
    lines += table(
        ["Sessions", "Cut-off p50 ms", "p95", "p99", "Stale frames", "Failed rounds",
         "Speech never heard (sent to TTS)", "Text never heard (written by LLM)", "Valid"],
        [[str(b["args"]["sessions"]), fmt(b["barge_in_cutoff_ms"], "p50"),
          fmt(b["barge_in_cutoff_ms"], "p95"), fmt(b["barge_in_cutoff_ms"], "p99"),
          str(b["stale_frames"]), str(b["failures"]), pct(eff.get("unheard_tts_share")),
          pct(eff.get("unheard_generated_share")), valid(b)]],
    )  # fmt: skip
    lines += [
        "The cut-off is dominated by a deliberate guard: while the agent is talking, the gateway "
        "needs 8 voiced frames out of the last 10 (about 160 ms of audio) before it treats a "
        "sound as an interruption, so noise and \"mm-hmm\" do not cut the agent off. The "
        "caller's clock starts at the first speech frame, so the 8th voiced frame arrives about "
        "140 ms later; the remainder is the gateway's own reaction time. The last two columns "
        "are large by design in this scenario: the caller interrupts 0.6 s into a reply that is "
        "several seconds long, and a fast LLM has usually finished writing before the caller "
        "hears the first word. Cancelling saves the speech synthesis and the playback, not much "
        "LLM work.",
        "",
        "## 3. Gateway versus a naive pipeline",
        "",
        "Provider set `bench-real`: STT 120 ms, LLM first token 250 ms plus 25 ms per word, TTS "
        "first audio 150 ms; the reply is three sentences. *Naive* is the same code with "
        "sentence streaming and barge-in switched off, so it waits for the whole reply before "
        "speaking and ignores the caller while talking.",
        "",
    ]
    rows = []
    for mode in ("gateway", "naive"):
        t = runs[f"compare-{mode}-turns"]["ttfa_ms"]
        barge = runs[f"compare-{mode}-barge"]
        cut, talk = barge["barge_in_cutoff_ms"], barge["talk_over_ms"]
        rows.append([
            mode, fmt(t, "p50"), fmt(t, "p95"),
            fmt(cut, "p50") if cut else "never stops", fmt(talk, "p50"),
            str(barge["stale_frames"]),
        ])  # fmt: skip
    lines += table(
        ["Mode", "TTFA p50 ms", "TTFA p95 ms", "Stops when interrupted (p50 ms)",
         "Agent keeps talking after interruption starts (p50 ms)", "Stale frames"],
        rows,
    )  # fmt: skip
    lines += [
        "**Caveat.** The stub TTS takes the same time regardless of text length, while real TTS "
        "takes longer for longer text, so the TTFA gap between the two modes is understated "
        "here. The barge-in difference does not depend on that.",
        "",
    ]
    DOCS.mkdir(exist_ok=True)
    path = DOCS / "results.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--quick", action="store_true", help="smaller matrix, about 2 minutes")
    parser.add_argument("--scale", help="comma-separated session counts for the scaling runs")
    args = parser.parse_args()

    try:
        import psutil  # noqa: F401  (the server's /api/process endpoint needs it)
    except ImportError:
        sys.exit('psutil is missing. Add "psutil" to dependencies in pyproject.toml, then '
                 'run: pip install -e ".[dev,vad,providers]"')  # fmt: skip

    scale = [int(x) for x in (args.scale or ("1,10,25" if args.quick else "1,10,50,100,200")).split(",")]
    turns = 3 if args.quick else 5
    ports = iter(range(8101, 8200))
    runs: dict[str, dict[str, Any]] = {}

    for n in scale:
        label = f"scale-n{n}"
        with Server(next(ports), "bench", "gateway") as server:
            runs[label] = run_loadgen(server.port, label, "turns", n, turns)

    with Server(next(ports), "bench", "gateway") as server:
        runs["barge-bench"] = run_loadgen(
            server.port, "barge-bench", "barge", 10 if args.quick else 20, 3 if args.quick else 4
        )

    for mode in ("gateway", "naive"):
        with Server(next(ports), "bench-real", mode) as server:
            for scenario, count, rounds in (("turns", 10, 4), ("barge", 10, 3)):
                label = f"compare-{mode}-{scenario}"
                runs[label] = run_loadgen(server.port, label, scenario, count, rounds)

    path = write_results(runs, scale)
    print(f"\nWrote {path}")


if __name__ == "__main__":
    main()